export const getLocalizedText = (text, isKn, dict = {}) => {
  if (!text) return '';
  if (!isKn) return text;
  if (dict[text]) return dict[text];

  // Check case-insensitive trim
  const clean = text.trim();
  for (const [key, val] of Object.entries(dict)) {
    if (key.toLowerCase() === clean.toLowerCase()) {
      return val;
    }
  }

  return text;
};

